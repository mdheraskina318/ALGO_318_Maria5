// Функція для введення додатного цілого числа
int getPositiveInt()
{
    int n;
    while (!(cin >> n) || n <= 0)
    {
        cout << "Введіть додатне ціле число: ";
        cin.clear();
        cin.ignore(10000, '\n');
    }
    return n;
}

// Функція для введення додатного дійсного числа
double getPositiveDouble()
{
    double value;
    while (!(cin >> value) || value <= 0)
    {
        cout << "Введіть додатне число: ";
        cin.clear();
        cin.ignore(10000, '\n');
    }
    return value;
}

// ЗАВДАННЯ 1. Варіант 26
// Визначення кількості точок у чорній області

void task1()
{
    int n;
    double a, r;
    double x, y;
    int count = 0;

    // Введення кількості точок
    cout << "Введіть кількість точок: ";
    n = getPositiveInt();

    // Введення сторони квадрата
    cout << "Введіть сторону квадрата a: ";
    a = getPositiveDouble();

    // Введення радіуса кола
    do
    {
        cout << "Введіть радіус кола r (r <= a/2): ";
        r = getPositiveDouble();

        if (r > a / 2)
            cout << "Радіус не повинен перевищувати a/2!" << endl;

    } while (r > a / 2);

    // Перевірка координат кожної точки
    for (int i = 1; i <= n; i++)
    {
        cout << "Введіть координати точки " << i << " (x, y): ";
        cin >> x >> y;

        // Перевірка належності чорній області
        if (x >= 0 && x <= a / 2 &&
            y >= x && y <= a / 2 &&
            x * x + y * y >= r * r)
        {
            count++;
        }
    }

    // Виведення результату
    cout << "Кількість точок у чорній області: "
         << count << endl;
}

// ЗАВДАННЯ 2. Варіант 12
// Обчислення суми ряду та виведення кожного третього елемента

void task2()
{
    int n;
    double x, sum = 0;
    double u, fact = 1;

    // Введення даних
    cout << "Введіть дійсне число x: ";
    cin >> x;

    cout << "Введіть натуральне число n: ";
    n = getPositiveInt();

    // Обчислення суми ряду
    for (int k = 1; k <= n; k++)
    {
        // Обчислення факторіала k!
        fact *= k;

        // Обчислення поточного елемента ряду
        u = pow(x - k, k + 1) / fact;

        // Додавання елемента до суми
        sum += u;

        // Виведення кожного третього елемента
        if (k % 3 == 0)
        {
            cout << "Елемент " << k << ": " << u << endl;
        }
    }

    // Виведення загальної суми
    cout << "Сума ряду S = " << sum << endl;
}

// ЗАВДАННЯ 3. Варіант 11
// Дослідження ряду на збіжність або розбіжність

void task3()
{
    double u, sum = 0;
    double g = 1E+5;
    int n = 1;

    // Початковий елемент ряду
    u = 6;

    cout << "Дослідження ряду на розбіжність:" << endl;

    // Обчислення елементів до досягнення граничного значення
    while (fabs(u) <= g)
    {
        // Виведення поточного елемента
        cout << "u" << n << " = " << u << endl;

        // Обчислення наростаючої суми
        sum += u;

        // Обчислення наступного елемента за рекурентною формулою
        u = u * (2.0 * n + 3) * (2.0 * n + 2) / (3.0 * n + 1);

        n++;
    }

    // Виведення результатів
    cout << "Наступний елемент перевищив g: " << u << endl;
    cout << "Часткова сума: " << sum << endl;

    cout << "Висновок: ряд розбіжний, оскільки його "
         << "загальний член не прямує до нуля." << endl;
}

